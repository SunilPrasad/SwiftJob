using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using SwiftJob.Domain.Emails;
using SwiftJob.Domain.Jobs;

namespace SwiftJob.Infrastructure.Persistence.Seeding;

/// <summary>
/// Seeds an empty database with clearly-marked sample jobs and emails for local development.
/// Sample Gmail ids start with <see cref="SampleMessageIdPrefix"/> and all URLs point at example.com.
/// Never runs against a database that already contains jobs.
/// </summary>
public sealed class SampleDataSeeder(AppDbContext db, TimeProvider timeProvider, ILogger<SampleDataSeeder> logger)
{
    public const string SampleMessageIdPrefix = "sample-";

    public async Task<int> SeedAsync(CancellationToken cancellationToken = default)
    {
        if (await db.Jobs.AnyAsync(cancellationToken))
        {
            logger.LogDebug("Database already contains jobs; sample data not seeded");
            return 0;
        }

        var now = timeProvider.GetUtcNow().UtcDateTime;
        var jobCount = 0;

        foreach (var sample in SampleEmails)
        {
            var receivedAt = now.AddHours(-sample.HoursAgo);
            var email = new JobEmail
            {
                GmailMessageId = SampleMessageIdPrefix + sample.MessageId,
                GmailThreadId = SampleMessageIdPrefix + sample.MessageId,
                Subject = sample.Subject,
                Sender = sample.Sender,
                ReceivedAt = receivedAt,
                BodyText = BuildBody(sample),
                SyncStatus = EmailSyncStatus.Processed,
                SyncedAt = now,
                ProcessedAt = now,
            };
            db.JobEmails.Add(email);

            foreach (var s in sample.Jobs)
            {
                var url = $"https://www.example.com/sample-jobs/{sample.Source.ToLowerInvariant()}/{s.SourceJobId}";
                var job = new Job
                {
                    Title = s.Title,
                    Company = s.Company,
                    SalaryText = s.SalaryText,
                    SalaryMin = s.SalaryMin,
                    SalaryMax = s.SalaryMax,
                    SalaryCurrency = s.SalaryText is null ? null : "GBP",
                    Location = s.Location,
                    WorkMode = s.WorkMode,
                    Description = s.Description,
                    Requirements = s.Requirements,
                    ApplicationUrl = url,
                    CanonicalUrl = url,
                    Source = sample.Source,
                    SourceJobId = s.SourceJobId,
                    ReceivedAt = receivedAt,
                };
                if (s.Status != JobStatus.New)
                {
                    job.ChangeStatus(s.Status, now);
                }

                job.EmailLinks.Add(new JobEmailLink { JobEmail = email, LinkedAt = now });
                db.Jobs.Add(job);
                jobCount++;
            }
        }

        await db.SaveChangesAsync(cancellationToken);
        logger.LogInformation("Seeded {JobCount} sample jobs from {EmailCount} sample emails", jobCount, SampleEmails.Count);
        return jobCount;
    }

    /// <summary>Deletes sample emails and the jobs that only came from them. Real data is untouched.</summary>
    /// <returns>Number of sample jobs removed.</returns>
    public async Task<int> RemoveAsync(CancellationToken cancellationToken = default)
    {
        var sampleEmails = await db.JobEmails
            .Where(e => e.GmailMessageId.StartsWith(SampleMessageIdPrefix))
            .ToListAsync(cancellationToken);
        var sampleEmailIds = sampleEmails.Select(e => e.Id).ToList();

        var jobs = await db.Jobs
            .Where(j => j.EmailLinks.Any()
                        && j.EmailLinks.All(l => sampleEmailIds.Contains(l.JobEmailId))
                        && !j.ApplicationSessions.Any())
            .ToListAsync(cancellationToken);

        db.Jobs.RemoveRange(jobs);
        db.JobEmails.RemoveRange(sampleEmails);
        await db.SaveChangesAsync(cancellationToken);
        logger.LogInformation("Removed {JobCount} sample jobs and {EmailCount} sample emails", jobs.Count, sampleEmails.Count);
        return jobs.Count;
    }

    public Task<int> CountAsync(CancellationToken cancellationToken = default) =>
        db.JobEmails.CountAsync(e => e.GmailMessageId.StartsWith(SampleMessageIdPrefix), cancellationToken);

    private static string BuildBody(SampleEmail sample) =>
        string.Join("\n\n", sample.Jobs.Select(j =>
            $"{j.Title}\n{j.Company ?? "Company not disclosed"} - {j.Location ?? "Location not specified"}\n" +
            $"{j.SalaryText ?? "Salary not specified"}\n" +
            $"View job: https://www.example.com/sample-jobs/{sample.Source.ToLowerInvariant()}/{j.SourceJobId}"))
        + "\n\n-- This is sample data generated by SwiftJob for local development. --";

